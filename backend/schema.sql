-- 1. Aggregates today's tracker status for dashboard
CREATE OR REPLACE FUNCTION get_dashboard_data(user_uuid UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    start_of_day TIMESTAMPTZ := date_trunc('day', NOW() AT TIME ZONE 'UTC');
    v_water_intake INT := 0;
    v_calorie_intake NUMERIC := 0;
    v_latest_weight JSONB := NULL;
BEGIN
    SELECT COALESCE(SUM(amount_ml), 0)
    INTO v_water_intake
    FROM water_logs
    WHERE user_id = user_uuid AND created_at >= start_of_day;

    SELECT COALESCE(SUM(calories), 0)
    INTO v_calorie_intake
    FROM food_logs
    WHERE user_id = user_uuid AND created_at >= start_of_day;

    SELECT to_jsonb(w)
    INTO v_latest_weight
    FROM (
        SELECT id, user_id, weight_kg, created_at
        FROM weight_logs
        WHERE user_id = user_uuid
        ORDER BY created_at DESC
        LIMIT 1
    ) w;

    RETURN jsonb_build_object(
        'todays_water_intake', v_water_intake,
        'todays_calorie_intake', v_calorie_intake,
        'latest_weight_log', v_latest_weight
    );
END;
$$;

-- 2. Calculates today's nutrient breakdown
CREATE OR REPLACE FUNCTION get_daily_nutrient_breakdown(user_uuid UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    start_of_day TIMESTAMPTZ := date_trunc('day', NOW() AT TIME ZONE 'UTC');
    v_total_calories NUMERIC := 0;
    v_macros JSONB := '{}'::jsonb;
    v_micros JSONB := '{}'::jsonb;
BEGIN
    SELECT COALESCE(SUM(calories), 0)
    INTO v_total_calories
    FROM food_logs
    WHERE user_id = user_uuid AND created_at >= start_of_day;

    RETURN jsonb_build_object(
        'total_calories', v_total_calories,
        'macros', v_macros,
        'micros', v_micros
    );
END;
$$;

-- 3. Provides aggregated weight history for chart visualization
CREATE OR REPLACE FUNCTION get_weight_history_for_chart(user_uuid UUID, days_ago INT DEFAULT 7)
RETURNS TABLE (
    log_date TIMESTAMPTZ,
    avg_weight NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        date_trunc('day', created_at) AS log_date,
        ROUND(AVG(weight_kg)::numeric, 2) AS avg_weight
    FROM weight_logs
    WHERE user_id = user_uuid 
      AND created_at >= (NOW() AT TIME ZONE 'UTC' - (days_ago || ' days')::interval)
    GROUP BY date_trunc('day', created_at)
    ORDER BY log_date ASC;
END;
$$;