-- ========= TABLES =========

-- 1. Stores unstructured journal entries from the user.
CREATE TABLE IF NOT EXISTS journal_entries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Stores comments from AI agents on specific journal entries.
CREATE TABLE IF NOT EXISTS journal_comments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    entry_id UUID REFERENCES journal_entries(id) ON DELETE CASCADE NOT NULL,
    agent_name VARCHAR(50) NOT NULL,
    comment_text TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Stores user profile information, including gamification elements.
CREATE TABLE IF NOT EXISTS user_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    username VARCHAR(50) UNIQUE,
    level INT DEFAULT 1,
    xp_points INT DEFAULT 0,
    xp_to_next_level INT DEFAULT 100,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Logs every user message and AI response for conversation history.
CREATE TABLE IF NOT EXISTS ai_interactions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    agent_name VARCHAR(50) NOT NULL,
    user_message TEXT NOT NULL,
    ai_response TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Stores the daily synthesis generated by the Master Overseer AI.
CREATE TABLE IF NOT EXISTS daily_summaries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    summary_text TEXT NOT NULL,
    date DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, date)
);

-- 6. Stores memory summaries and token counts for each user/agent pair.
CREATE TABLE IF NOT EXISTS memory_stats (
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    agent_name VARCHAR(50) NOT NULL,
    cumulative_summary TEXT,
    summarized_until_timestamp TIMESTAMPTZ,
    active_token_count INT NOT NULL DEFAULT 0,
    last_updated TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (user_id, agent_name)
);

-- 7. Stores body weight logs over time.
CREATE TABLE IF NOT EXISTS weight_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    weight_kg NUMERIC NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Stores water consumption logs.
CREATE TABLE IF NOT EXISTS water_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    amount_ml INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Stores detailed food & nutrition logs.
CREATE TABLE IF NOT EXISTS food_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    food_name TEXT NOT NULL,
    meal_type VARCHAR(50) NOT NULL,
    serving_size TEXT,
    calories NUMERIC NOT NULL DEFAULT 0,
    macros JSONB DEFAULT '{}'::jsonb,
    micros JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Stores user daily tracker goals.
CREATE TABLE IF NOT EXISTS user_goals (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    daily_water_goal_ml INT,
    daily_calorie_goal INT,
    weight_goal_kg NUMERIC,
    weight_goal_type VARCHAR(50),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);


